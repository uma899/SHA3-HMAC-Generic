`timescale 1ns / 1ps
// ---------------------------------------------------------------------------
// Keccak-f[1600] round constants.
// Only bits 0,1,3,7,15,31,63 (= 2^j - 1) of any RC are ever non-zero, so the
// table is 24 x 7 bits and the other 57 bits are tied to 0.
// ---------------------------------------------------------------------------
module round_constant (
    input  wire [4:0]  round,
    output wire [63:0] RC
);
    reg [6:0] t;                         // t[j] -> RC[2^j - 1]
    always @(*) begin
        case (round)
            5'd0 : t = 7'b0000001;   // 0000000000000001
            5'd1 : t = 7'b0011010;   // 0000000000008082
            5'd2 : t = 7'b1011110;   // 800000000000808A
            5'd3 : t = 7'b1110000;   // 8000000080008000
            5'd4 : t = 7'b0011111;   // 000000000000808B
            5'd5 : t = 7'b0100001;   // 0000000080000001
            5'd6 : t = 7'b1111001;   // 8000000080008081
            5'd7 : t = 7'b1010101;   // 8000000000008009
            5'd8 : t = 7'b0001110;   // 000000000000008A
            5'd9 : t = 7'b0001100;   // 0000000000000088
            5'd10: t = 7'b0110101;   // 0000000080008009
            5'd11: t = 7'b0100110;   // 000000008000000A
            5'd12: t = 7'b0111111;   // 000000008000808B
            5'd13: t = 7'b1001111;   // 800000000000008B
            5'd14: t = 7'b1011101;   // 8000000000008089
            5'd15: t = 7'b1010011;   // 8000000000008003
            5'd16: t = 7'b1010010;   // 8000000000008002
            5'd17: t = 7'b1001000;   // 8000000000000080
            5'd18: t = 7'b0010110;   // 000000000000800A
            5'd19: t = 7'b1100110;   // 800000008000000A
            5'd20: t = 7'b1111001;   // 8000000080008081
            5'd21: t = 7'b1011000;   // 8000000000008080
            5'd22: t = 7'b0100001;   // 0000000080000001
            5'd23: t = 7'b1110100;   // 8000000080008008
            default: t = 7'b0000000;
        endcase
    end

    assign RC = {t[6], 31'b0, t[5], 15'b0, t[4], 7'b0, t[3], 3'b0, t[2], 1'b0, t[1], t[0]};
endmodule
